/** The phone's language, if it's one of ours; else English. */
export function guessLang(list = navigator.languages || [navigator.language]) {
  for (const l of list) {
    const low = String(l).toLowerCase();
    if (low.startsWith('zh')) return 'zh-TW';      // Taiwan first; simplified readers get by
    const hit = LANGS.find((x) => low.startsWith(x.code.toLowerCase()));
    if (hit) return hit.code;
  }
  return 'en';
}

/** Words for `lang` (missing ones fall back to English). */
export function words(lang) {
  const t = T[lang] || T.en;
  return new Proxy(t, { get: (o, k) => o[k] ?? T.en[k] });
}

/** Text for the rig's English-only screens: accents off (Nguyễn -> Nguyen), other
 *  scripts dropped. Callers that need something left check for ''. */
export function ascii(s) {
  return String(s ?? '').normalize('NFD').replace(/[̀-ͯ]/g, '')
    .replace(/đ/g, 'd').replace(/Đ/g, 'D').replace(/[^ -~]/g, '');
}
