export const PIC_MS = 20000;          // how long a picture stays up
export const TEXT_MS = 10000;         // how long a typed word stays up

const norm = (w) => w.toLowerCase().replace(/[^a-z0-9]/g, '');
const INDEX = new Map();
for (const [id, p] of Object.entries(PICS)) {
  p.id = id;
  INDEX.set(id, p);
  for (const w of p.words) INDEX.set(norm(w), p);
}
CENSORED.id = 'censor';
for (const w of CENSORED.words) INDEX.set(norm(w), CENSORED);

/** The library entry for a word or phrase ("trick or treat" -> pumpkin), or null. */
export function lookup(text) {
  const whole = norm(text);
  if (INDEX.has(whole)) return INDEX.get(whole);
  for (const w of text.split(/\s+/)) if (INDEX.has(norm(w))) return INDEX.get(norm(w));
  return null;
}

/** Art -> palette (up to 16, index 0 = background black) + 16 rows of indexes. */
export function indexed(p) {
  const keys = Object.keys(p.pal);
  const palette = ['#000000', ...keys.map((k) => p.pal[k])];
  const rows = p.art.map((row) => [...row].map((ch) => (ch === '.' ? 0 : keys.indexOf(ch) + 1)));
  return { palette, rows };
}
